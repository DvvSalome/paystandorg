#!/usr/bin/env python3
"""Generates supabase/migrations/20261112000000_eva_view.sql from supabase/eva_question_map.json.
The view `intake_rows` is what Eva's pipeline reads (ingest.supabase.table): one column per
question, named exactly like QUESTION_MAP, plus application_id and a timestamp column."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
m = json.loads((root / "supabase" / "eva_question_map.json").read_text())
FILES = {"C1", "C2", "J3"}          # questions whose value is an uploaded document
cols = []
for qid, header in m["map"]:
    assert header.replace("_", "").isalnum(), header
    if qid in FILES:
        expr = (f"coalesce((select 'storage:' || f.storage_path from application_files f "
                f"where f.application_id = a.application_id and f.question = '{qid}'), '')")
    else:
        expr = f"intake_text(a.answers, '{qid}')"
    cols.append(f'  {expr} as "{header}"')
sql = f"""-- Eva's read model. GENERATED by scripts/gen-eva-view.py from supabase/eva_question_map.json. Do not edit by hand.
-- One row per completed application, one column per question, named like QUESTION_MAP in intake_pipeline.py.

-- Text value of one answer. A list of options (checkboxes) is joined with '; '.
create or replace function intake_text(answers jsonb, k text) returns text
language sql immutable as $$
  select case jsonb_typeof(answers -> k)
    when 'array'  then (select coalesce(string_agg(x, '; '), '') from jsonb_array_elements_text(answers -> k) x)
    else coalesce(answers ->> k, '')
  end
$$;

create or replace view intake_rows with (security_invoker = true) as
select
  a.application_id,
  date_trunc('second', a.finalized_at) as created_at,
  date_trunc('second', a.finalized_at) as "{m['timestamp']}",
{(","+chr(10)).join(cols)}
from applications a
where a.status = 'complete'
  and a.finalized_at <= now() - interval '2 minutes';   -- settle delay: nothing can arrive "late" behind the watermark

-- Lock everything down. Supabase gives anon/authenticated access to new objects in `public` by default;
-- the publishable key must never read applications, files, the counter or this view.
revoke all on applications, application_files, rate_events, intake_rows from anon, authenticated;
revoke execute on function next_application_id() from public, anon, authenticated;
revoke execute on function intake_text(jsonb, text) from public, anon, authenticated;
grant  execute on function next_application_id() to service_role;
grant  execute on function intake_text(jsonb, text) to service_role;
grant  select on intake_rows to service_role;
revoke all on sequence application_seq from anon, authenticated;
grant  usage, select on sequence application_seq to service_role;
"""
out = root / "supabase" / "migrations" / "20261112000000_eva_view.sql"
out.write_text(sql)
print(out.relative_to(root), len(m["map"]), "preguntas")
